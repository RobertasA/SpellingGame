#!/usr/bin/env node
"use strict";
/* Looks for recordings under v2/voice/ and writes:
     manifest.js        which clip the game plays for which text
     RECORDING-LIST.md  a checklist of everything the game can say
   Run it again after adding or removing files:  node v2/voice/build-manifest.js
   No packages needed. */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const VOICE_DIR = __dirname;
const JS_DIR = path.join(VOICE_DIR, "..", "js");
const AUDIO = /\.(mp3|m4a|ogg|oga|wav|webm|aac|flac)$/i;

/* ---- the clips that are there ---- */
function scan(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(full, out);
    else if (AUDIO.test(entry.name)) {
      const slug = entry.name.replace(AUDIO, "").toLowerCase();
      const rel = path.relative(VOICE_DIR, full).split(path.sep).join("/");
      if (out[slug]) console.warn(`  ! two files for "${slug}": keeping ${out[slug]}, ignoring ${rel}`);
      else out[slug] = rel;
    }
  }
  return out;
}
const clips = scan(VOICE_DIR, {});

/* ---- the game's own list of what it says (loaded, not copied) ---- */
const noop = () => {};
const ctx = {
  console, URL, Blob: class {}, Math, JSON, Promise, setTimeout, clearTimeout,
  localStorage: { getItem: () => null, setItem: noop },
  document: { getElementById: () => ({ style: {}, classList: { add: noop, remove: noop } }) },
  Audio: class { constructor() { this.volume = 1; } play() { return Promise.resolve(); } pause() {} },
};
ctx.window = ctx;                      // so "speechSynthesis" in window is false, as in a browser without it
vm.createContext(ctx);
for (const f of ["words.js", "core.js", "voice.js"]) {
  vm.runInContext(fs.readFileSync(path.join(JS_DIR, f), "utf8"), ctx, { filename: f });
}
const catalogue = vm.runInContext("voiceCatalogue()", ctx);

/* ---- manifest.js ---- */
const sorted = Object.fromEntries(Object.entries(clips).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(path.join(VOICE_DIR, "manifest.js"),
`/* Generated by voice/build-manifest.js — do not edit by hand.
   Maps a clip name to its audio file (relative to this folder). */
window.VOICE_MANIFEST = ${Object.keys(sorted).length ? JSON.stringify(sorted, null, 2) : "{}"};
`);

/* ---- RECORDING-LIST.md ---- */
const known = new Set(catalogue.map(c => c.slug));
const groups = [];
for (const c of catalogue) {
  let g = groups.find(x => x.name === c.group);
  if (!g) groups.push(g = { name: c.group, items: [] });
  g.items.push(c);
}
const have = catalogue.filter(c => clips[c.slug]).length;
let md = `# Recording list

Generated by \`node v2/voice/build-manifest.js\` — do not edit by hand.
**${have} of ${catalogue.length}** recorded. Save each clip under the name shown (any of mp3, m4a, ogg, wav, webm).
Words go in \`words/\`, sentences in \`lines/\`.
`;
for (const g of groups) {
  const done = g.items.filter(c => clips[c.slug]).length;
  md += `\n## ${g.name} (${done}/${g.items.length})\n\n`;
  for (const c of g.items) {
    const dir = c.kind === "word" ? "words" : "lines";
    md += clips[c.slug]
      ? `- [x] ${c.text} — \`${clips[c.slug]}\`\n`
      : `- [ ] ${c.text} — \`${dir}/${c.slug}.mp3\`\n`;
  }
}
fs.writeFileSync(path.join(VOICE_DIR, "RECORDING-LIST.md"), md);

const stray = Object.keys(clips).filter(s => !known.has(s));
console.log(`${Object.keys(clips).length} audio file(s) found; ${have} of ${catalogue.length} lines and words recorded.`);
if (stray.length) console.log(`Not matching anything the game says (kept anyway): ${stray.join(", ")}`);
console.log("Wrote manifest.js and RECORDING-LIST.md");
